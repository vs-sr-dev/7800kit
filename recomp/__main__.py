"""Recompile a 7800 cartridge to C++ and build it.

    python -m 7800kit.recomp ROM.a78 --trace TRACEDIR --out build/recomp/GAME [--build]
    build/recomp/GAME/a78.exe ROM.a78 --lockstep --frames 6000

The output directory gets `regions.h` (a function per region),
`region_F.cpp` / `region_B<n>.cpp` (the code), `register.cpp` (an entry
thunk per entry and `a78_register_all`), and with --build `a78.exe`: the
runtime (7800kit/runtime) linked with the game's code, built with g++
(msys2's ucrt64; SDL2 for --window when it is there).
"""
import argparse
import concurrent.futures
import os
import shutil
import subprocess
import sys

from .. import cart as cartmod
from . import discover, emit
from .discover import ename

HERE = os.path.dirname(os.path.abspath(__file__))
RUNTIME = os.path.join(os.path.dirname(HERE), 'runtime')
RUNTIME_SRC = ['a78_core.cpp', 'a78_audio.cpp', 'a78_main.cpp']
GXX_DIR = os.environ.get('A78_GXX_DIR', r'C:\msys64\ucrt64\bin')   # msys2's ucrt64 g++


def generate(rom, trace, out, comments=True, log=print):
    c = cartmod.Cart.load(rom)
    tr = discover.Trace(trace, c) if trace else None
    prog = discover.Program(c, tr).discover()
    os.makedirs(out, exist_ok=True)
    regions = [prog.regions[s] for s in sorted(prog.regions)]
    with open(os.path.join(out, 'regions.h'), 'w') as f:
        f.write('// generated by 7800kit.recomp from %s\n#pragma once\n#include "a78.h"\n'
                % os.path.basename(rom))
        for r in regions:
            f.write(f'void {r.name}(A78& c, uint16_t e);\n')
    sites = {}
    files = []
    for r in regions:
        path = os.path.join(out, f'region_{r.name[2:]}.cpp')
        files.append(path)
        b = emit.Body(prog, r, comments)
        text = '\n'.join(b.emit())
        with open(path, 'w') as f:
            f.write('// generated by 7800kit.recomp\n#include "regions.h"\n\n' + text + '\n')
        for k, v in b.sites.items():
            sites[k] = sites.get(k, 0) + v
    with open(os.path.join(out, 'register.cpp'), 'w') as f:
        f.write('// generated by 7800kit.recomp\n#include "regions.h"\n\n')
        for r in regions:
            for e in sorted(r.entries):
                f.write(f'static void {ename(r.slot, e)}(A78& c) {{ {r.name}(c, 0x{e:04X}); }}\n')
        f.write('\nvoid a78_register_all() {\n')
        for r in regions:
            for e in sorted(r.entries):
                f.write(f'    a78_register({r.slot}, 0x{e:04X}, {ename(r.slot, e)});\n')
        f.write('}\n')
    files.append(os.path.join(out, 'register.cpp'))
    insns = sum(len(r.code) for r in regions)
    ents = sum(len(r.entries) for r in regions)
    log(f'{c.name}: {len(regions)} regions, {ents} entries, {insns} instructions; '
        + ', '.join(f'{k} {v}' for k, v in sorted(sites.items())))
    cov = prog.coverage()
    if cov:
        log(f'  traced instructions held by a region: {cov[0]}/{cov[1]}')
    return files


def build(out, files, opt='-O1', log=print, history=False):
    env = dict(os.environ)
    if os.path.isdir(GXX_DIR):
        env['PATH'] = GXX_DIR + os.pathsep + env.get('PATH', '')
    gxx = shutil.which('g++', path=env['PATH']) or 'g++'
    sdl = os.path.isfile(os.path.join(os.path.dirname(GXX_DIR), 'include', 'SDL2', 'SDL.h'))
    flags = ['-std=c++17', opt, '-w', f'-I{RUNTIME}', f'-I{out}']
    if sdl:
        flags.append('-DA78_SDL')
    if history:
        flags.append('-DA78_HISTORY')
    objs_dir = os.path.join(out, 'obj' + ('_hist' if history else ''))
    os.makedirs(objs_dir, exist_ok=True)
    srcs = [os.path.join(RUNTIME, s) for s in RUNTIME_SRC] + files
    newest_rt = max(os.path.getmtime(os.path.join(RUNTIME, n)) for n in os.listdir(RUNTIME)
                    if n.endswith(('.h', '.cpp')))

    def cc(src):
        obj = os.path.join(objs_dir, os.path.splitext(os.path.basename(src))[0] + '.o')
        if os.path.exists(obj) and src not in files and os.path.getmtime(obj) > newest_rt:
            return obj
        rflags = [f if f != opt or src not in files else opt for f in flags]
        if src not in files:
            rflags = [('-O2' if f == opt else f) for f in flags]
        r = subprocess.run([gxx, *rflags, '-c', src, '-o', obj], env=env,
                           capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError(f'{src}:\n{r.stderr[:4000]}')
        return obj
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as ex:
        objs = list(ex.map(cc, srcs))
    exe = os.path.join(out, 'a78.exe')
    libs = ['-lmingw32', '-lSDL2main', '-lSDL2'] if sdl else []
    r = subprocess.run([gxx, *objs, '-o', exe, '-static-libgcc', '-static-libstdc++', *libs],
                       env=env, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stderr[:4000])
    dll = os.path.join(GXX_DIR, 'SDL2.dll')
    if sdl and os.path.isfile(dll) and not os.path.exists(os.path.join(out, 'SDL2.dll')):
        shutil.copy2(dll, out)
    log(f'  built {exe}')
    return exe


def main(argv=None):
    ap = argparse.ArgumentParser(prog='7800kit.recomp')
    ap.add_argument('rom')
    ap.add_argument('--trace')
    ap.add_argument('--out', required=True)
    ap.add_argument('--build', action='store_true')
    ap.add_argument('--no-comments', action='store_true')
    ap.add_argument('-O', dest='opt', default='1')
    ap.add_argument('--history', action='store_true', help='record the last instructions (debugging)')
    a = ap.parse_args(argv)
    files = generate(a.rom, a.trace, a.out, comments=not a.no_comments)
    if a.build:
        build(a.out, files, opt='-O' + a.opt, history=a.history)


if __name__ == '__main__':
    sys.exit(main())
